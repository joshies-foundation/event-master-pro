CREATE OR REPLACE FUNCTION public.submit_bet_canceled_by_gm(bet_id bigint)
 RETURNS void
 LANGUAGE plpgsql
AS $function$DECLARE
  v_requester_player_id int8;
  v_requester_wager int8;
  v_requester_name text;
  v_opponent_player_id int8;
  v_opponent_wager int8;
  v_opponent_name text;
  v_description text;
  v_old_status bet_status;
  v_unwound int := 0;
BEGIN
  SELECT
    requester_player_id,
    requester_wager,
    opponent_player_id,
    opponent_wager,
    description,
    status
  INTO
    v_requester_player_id,
    v_requester_wager,
    v_opponent_player_id,
    v_opponent_wager,
    v_description,
    v_old_status
  FROM bet
  WHERE id = bet_id
  FOR UPDATE;

  IF v_old_status IN ('requester_won', 'opponent_won', 'push') THEN
    DELETE FROM transaction WHERE settles_bet_id = bet_id;
    GET DIAGNOSTICS v_unwound = ROW_COUNT;
  END IF;

  IF v_old_status = 'active' OR v_unwound > 0 THEN
    SELECT u.display_name
    INTO v_requester_name
    FROM player p
    JOIN "user" u ON p.user_id = u.id
    WHERE p.id = v_requester_player_id;

    SELECT u.display_name
    INTO v_opponent_name
    FROM player p
    JOIN "user" u ON p.user_id = u.id
    WHERE p.id = v_opponent_player_id;

    INSERT INTO transaction
      (player_id,
      num_points,
      description,
      settles_bet_id,
      created_at,
      updated_at)
    VALUES (
      v_requester_player_id,
      v_requester_wager,
      'Canceled by GM: Bet against ' || v_opponent_name || ' that ''' || v_description || '''',
      bet_id,
      now(),
      now());

    INSERT INTO transaction
      (player_id,
      num_points,
      description,
      settles_bet_id,
      created_at,
      updated_at)
    VALUES (
      v_opponent_player_id,
      v_opponent_wager,
      'Canceled by GM: ' || v_requester_name || '''s bet that ''' || v_description || '''',
      bet_id,
      now(),
      now());
  END IF;

  UPDATE bet
  SET status = 'canceled_by_gm'
  WHERE id = bet_id;
END;$function$;

CREATE OR REPLACE FUNCTION public.submit_bet_accepted(bet_id bigint)
 RETURNS void
 LANGUAGE plpgsql
AS $function$DECLARE
  v_requester_player_id int8;
  v_requester_wager int8;
  v_requester_name text;
  v_opponent_player_id int8;
  v_opponent_wager int8;
  v_opponent_name text;
  v_description text;
  v_status bet_status;
  v_bet_type bet_type;
  v_details jsonb;
BEGIN
  SELECT
    requester_player_id,
    requester_wager,
    opponent_player_id,
    opponent_wager,
    description,
    status,
    bet_type,
    details
  INTO
    v_requester_player_id,
    v_requester_wager,
    v_opponent_player_id,
    v_opponent_wager,
    v_description,
    v_status,
    v_bet_type,
    v_details
  FROM bet
  WHERE id = bet_id
  FOR UPDATE;

  IF v_status IS DISTINCT FROM 'pending_acceptance' THEN
    RAISE EXCEPTION 'This bet is no longer waiting to be accepted.';
  END IF;

  IF (v_bet_type = 'duel' AND NOT EXISTS (
        SELECT 1 FROM duel WHERE id = (v_details->>'duelId')::int8 FOR SHARE))
     OR (v_bet_type = 'special_space_event' AND NOT EXISTS (
        SELECT 1 FROM special_space_event WHERE id = (v_details->>'ssEventId')::int8 FOR SHARE))
     OR (v_bet_type = 'chaos_space_event' AND NOT EXISTS (
        SELECT 1 FROM chaos_space_event WHERE id = (v_details->>'chaosEventId')::int8 FOR SHARE)) THEN
    RAISE EXCEPTION 'The duel or space event for this bet no longer exists. Reject the bet instead.';
  END IF;

  SELECT u.display_name
  INTO v_requester_name
  FROM player p
  JOIN "user" u ON p.user_id = u.id
  WHERE p.id = v_requester_player_id;

  SELECT u.display_name
  INTO v_opponent_name
  FROM player p
  JOIN "user" u ON p.user_id = u.id
  WHERE p.id = v_opponent_player_id;

  INSERT INTO transaction
    (player_id,
    num_points,
    description,
    created_at,
    updated_at)
  VALUES (
    v_requester_player_id,
    -v_requester_wager,
    'Wager for bet against ' || v_opponent_name || ' that ''' || v_description || '''',
    now(),
    now());

  INSERT INTO transaction
    (player_id,
    num_points,
    description,
    created_at,
    updated_at)
  VALUES (
    v_opponent_player_id,
    -v_opponent_wager,
    'Wager for ' || v_requester_name || '''s bet that ''' || v_description || '''',
    now(),
    now());

  UPDATE bet
  SET status = 'active'
  WHERE id = bet_id;
END;$function$;

CREATE OR REPLACE FUNCTION public.resolve_gameboard_move_bets()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$declare
	bet_row RECORD;
	_submit_id int8 := public.find_round_submit_id(
		(select session_id from public.player where id = NEW.player_id),
		NEW.round_number,
		'gameboard_moves');
	_outcome bet_status;
begin
	for bet_row in
		select
			id,
			status,
			settled_by_round_submit_id,
			(details->>'gameboardSpaceId')::int8 as gameboard_space_id
		from
			bet
		where
			bet_type = 'gameboard_move' and
			(details->>'playerId')::int8 = NEW.player_id
	loop
		if bet_row.status = 'pending_acceptance' then
			perform submit_bet_canceled_by_gm(bet_row.id);
			continue;
		end if;

		_outcome := case when NEW.gameboard_space_id = bet_row.gameboard_space_id
			then 'requester_won' else 'opponent_won' end;

		if bet_row.status in ('requester_won', 'opponent_won')
			and bet_row.settled_by_round_submit_id = _submit_id then
			if bet_row.status = _outcome then
				continue;
			end if;
			delete from transaction where settles_bet_id = bet_row.id;
		elsif bet_row.status != 'active' then
			continue;
		end if;

		if _outcome = 'requester_won' then
			perform submit_bet_requester_won(bet_row.id);
		else
			perform submit_bet_opponent_won(bet_row.id);
		end if;

		update bet set settled_by_round_submit_id = _submit_id where id = bet_row.id;
	end loop;
	return NEW;
end;$function$;

CREATE OR REPLACE FUNCTION public.log_round_moves (
  playermoves json,
  roundnumber integer
)
  RETURNS void
  LANGUAGE plpgsql
  AS $function$DECLARE
    v_player_id INT;
    distance_traveled INT;
    v_gameboard_space_id INT;
    points_gained INT;
    space_name TEXT;
    gameboard_space_effect TEXT;
    decision TEXT;
    values JSON;
    num_players_who_landed_on_bank_space INT;
    v_bank_balance BIGINT;
    points_to_gain INT;
    chance_points_amount INT;
    _session_id BIGINT;
    _submit_id BIGINT;
    _paid_out BIGINT;
    _bet_id BIGINT;
    _event_submit_id BIGINT;
BEGIN
    PERFORM 1 FROM game_state
    WHERE id = 1 AND round_phase = 'gameboard_moves' AND round_number = roundnumber
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Round % is not waiting for gameboard moves', roundnumber;
    END IF;

    SELECT session_id INTO _session_id FROM game_state WHERE id = 1;
    PERFORM 1 FROM session WHERE id = _session_id FOR NO KEY UPDATE;

    _submit_id := open_round_submit(_session_id, roundnumber, 'gameboard_moves');
    SELECT bank_paid_out INTO _paid_out FROM round_submit WHERE id = _submit_id;

    FOR _bet_id IN
        SELECT b.id FROM bet b
        WHERE (b.status IN ('pending_acceptance', 'active')
               OR (b.status IN ('requester_won', 'opponent_won', 'push')
                   AND EXISTS (SELECT 1 FROM transaction t WHERE t.settles_bet_id = b.id)))
          AND ((b.bet_type = 'duel' AND (b.details->>'duelId')::int8 IN (
                  SELECT d.id FROM duel d WHERE d.round_submit_id = _submit_id))
            OR (b.bet_type = 'special_space_event' AND (b.details->>'ssEventId')::int8 IN (
                  SELECT e.id FROM special_space_event e WHERE e.round_submit_id = _submit_id))
            OR (b.bet_type = 'chaos_space_event' AND (b.details->>'chaosEventId')::int8 IN (
                  SELECT e.id FROM chaos_space_event e WHERE e.round_submit_id = _submit_id)))
    LOOP
        PERFORM submit_bet_canceled_by_gm(_bet_id);
    END LOOP;

    _event_submit_id := find_round_submit_id(_session_id, roundnumber, 'event');
    IF _event_submit_id IS NOT NULL THEN
        PERFORM take_back_event_results(_event_submit_id, '{}');
    END IF;

    IF _paid_out > 0 THEN
        UPDATE session SET bank_balance = bank_balance + _paid_out WHERE id = _session_id;
        UPDATE round_submit SET bank_paid_out = 0 WHERE id = _submit_id;
    END IF;

    DELETE FROM transaction WHERE round_submit_id = _submit_id;

    DELETE FROM duel WHERE round_submit_id = _submit_id;
    DELETE FROM special_space_event WHERE round_submit_id = _submit_id;
    DELETE FROM chaos_space_event WHERE round_submit_id = _submit_id;
    DELETE FROM gameboard_move gm USING player p
    WHERE p.id = gm.player_id AND p.session_id = _session_id AND gm.round_number = roundnumber;

    num_players_who_landed_on_bank_space := (SELECT COUNT(*) FROM json_object_keys(playerMoves::json) pm WHERE (playerMoves->pm->>'gameboardSpaceId')::INT IN (SELECT id FROM gameboard_space gs WHERE gs.effect = 'bank'));

    FOR v_player_id, values IN SELECT * FROM json_each_text(playerMoves::json)
    LOOP
        v_gameboard_space_id := values -> 'gameboardSpaceId';
        distance_traveled := values -> 'distanceTraveled';
        chance_points_amount := values -> 'chancePointsAmount';

        SELECT effect, effect_data->>'pointsGained', name INTO gameboard_space_effect, points_gained, space_name
        FROM gameboard_space WHERE id = v_gameboard_space_id;

        SELECT values ->> 'decision' INTO decision;

        INSERT INTO gameboard_move (player_id, round_number, distance_traveled, gameboard_space_id, created_at, updated_at)
        VALUES (v_player_id, roundNumber, distance_traveled, v_gameboard_space_id, now(), now());

        IF gameboard_space_effect = 'gain_points' OR
           (gameboard_space_effect = 'gain_points_or_do_activity' AND decision = 'points') THEN
            INSERT INTO transaction (player_id, num_points, description, round_submit_id, lost_to_bank, created_at, updated_at)
            VALUES (v_player_id, points_gained, space_name || ' Space on turn ' || roundNumber, _submit_id, points_gained < 0, now(), now());
        END IF;

        IF gameboard_space_effect = 'special' THEN
            INSERT INTO special_space_event (session_id, round_number, player_id, status, special_space_id, round_submit_id, created_at, updated_at)
            VALUES (_session_id, roundNumber, v_player_id, 'event_not_selected', v_gameboard_space_id, _submit_id, now(), now());
        END IF;

        IF gameboard_space_effect = 'duel' THEN
            INSERT INTO duel (session_id, round_number, challenger_player_id, status, duel_space_id, round_submit_id, created_at, updated_at)
            VALUES (_session_id, roundNumber, v_player_id, 'opponent_not_selected', v_gameboard_space_id, _submit_id, now(), now());
        END IF;

        IF gameboard_space_effect = 'chaos' THEN
            INSERT INTO chaos_space_event (session_id, round_number, player_id, status, chaos_space_id, round_submit_id, created_at, updated_at)
            VALUES (_session_id, roundNumber, v_player_id, 'event_not_selected', v_gameboard_space_id, _submit_id, now(), now());
        END IF;

        IF gameboard_space_effect = 'bank' THEN
            SELECT bank_balance INTO v_bank_balance FROM session WHERE id = _session_id;
            IF v_bank_balance < 0 THEN
                RAISE EXCEPTION 'Replaying round % would pay the bank space from a bank of % points. Raise the bank with Override Bank Balance, then submit again.', roundnumber, v_bank_balance;
            END IF;

            points_to_gain := v_bank_balance / num_players_who_landed_on_bank_space;

            INSERT INTO transaction (player_id, num_points, description, round_submit_id, created_at, updated_at)
            VALUES (v_player_id, points_to_gain, space_name || ' Space on turn ' || roundNumber, _submit_id, now(), now());
        END IF;

        IF gameboard_space_effect = 'chance_points' THEN
            INSERT INTO transaction (player_id, num_points, description, round_submit_id, lost_to_bank, created_at, updated_at)
            VALUES (v_player_id, chance_points_amount, space_name || ' Space on turn ' || roundNumber, _submit_id, chance_points_amount < 0, now(), now());
        END IF;
    END LOOP;

    IF num_players_who_landed_on_bank_space > 0 THEN
        UPDATE round_submit
        SET bank_paid_out = (SELECT bank_balance FROM session WHERE id = _session_id)
        WHERE id = _submit_id;
        UPDATE session SET bank_balance = 0 WHERE id = _session_id;
    END IF;

    SELECT bank_balance INTO v_bank_balance FROM session WHERE id = _session_id;
    IF v_bank_balance < 0 THEN
        RAISE EXCEPTION 'Replaying round % would take the bank to % points. Raise the bank with Override Bank Balance, then submit again.', roundnumber, v_bank_balance;
    END IF;

    WITH reopened AS (
        UPDATE bet b
        SET status = 'active', settled_by_round_submit_id = NULL
        WHERE b.settled_by_round_submit_id = _submit_id
          AND b.status IN ('requester_won', 'opponent_won')
          AND NOT EXISTS (
              SELECT 1 FROM gameboard_move gm
              WHERE gm.player_id = (b.details->>'playerId')::int8
                AND gm.round_number = roundnumber)
        RETURNING b.id
    )
    DELETE FROM transaction t USING reopened r WHERE t.settles_bet_id = r.id;

    UPDATE game_state SET round_phase = 'special_space_events' WHERE id = 1;

    RETURN;
END;$function$;

CREATE OR REPLACE FUNCTION public.end_round (
  _round_number      integer,
  team_score_changes jsonb
)
  RETURNS jsonb
  LANGUAGE plpgsql
  AS $function$
declare
    event_team_id int8;
    points int8;
    team_player_id int8;
    event_name text;
    _session_id int8;
    _auto_mint boolean;
    _max_points int8;
    _token_recipient_user_ids uuid[] := '{}';
    _submit_id int8;
    _winners int8[] := '{}';
    _player_id int8;
begin
    perform 1 from game_state
    where id = 1 and round_phase = 'event' and round_number = _round_number
    for update;
    if not found then
        raise exception 'Round % is not waiting for event results', _round_number;
    end if;

    select session_id into _session_id from game_state where id = 1;

    _submit_id := public.open_round_submit(_session_id, _round_number, 'event');

    select name into event_name from event
    where session_id = _session_id and round_number = _round_number;

    select prize_token_on_event_win into _auto_mint
    from session where id = _session_id;

    select max((value)::int8) into _max_points
    from jsonb_each_text(team_score_changes) as t(key, value);

    if _auto_mint and _max_points > 0 then
        select coalesce(array_agg(distinct ep.player_id), '{}') into _winners
        from jsonb_each_text(team_score_changes) as t(team_id, team_points)
        join public.event_participant ep on ep.team_id = t.team_id::int8
        join public.player p on p.id = ep.player_id and p.enabled
        where t.team_points::int8 = _max_points;
    end if;

    perform public.take_back_event_results(_submit_id, _winners);

    for event_team_id, points in select * from jsonb_each_text(team_score_changes) loop
        for team_player_id in
            select player_id from event_participant where team_id = event_team_id
        loop
            insert into public.transaction (player_id, num_points, description, round_submit_id)
            values (team_player_id, points, 'Points earned from ' || event_name, _submit_id);

            insert into public.player_round_score (player_id, round_number, score)
            values (team_player_id, _round_number,
                (select score from public.player where id = team_player_id)
            )
            on conflict on constraint player_round_score_player_id_round_number_key
            do update set score = excluded.score;
        end loop;
    end loop;

    for _player_id in
        select w.player_id from unnest(_winners) as w(player_id)
        where not exists (
            select 1 from public.prize_token_award a
            where a.round_submit_id = _submit_id and a.player_id = w.player_id)
    loop
        update public.player
        set prize_tokens = prize_tokens + 1,
            updated_at = now()
        where id = _player_id;

        insert into public.prize_token_award (round_submit_id, player_id)
        values (_submit_id, _player_id);

        _token_recipient_user_ids := _token_recipient_user_ids ||
            (select user_id from public.player where id = _player_id);
    end loop;

    update public.game_state
    set round_phase = 'waiting_for_next_round'
    where id = 1;

    return jsonb_build_object('token_recipient_user_ids', _token_recipient_user_ids);
end;
$function$;

CREATE OR REPLACE FUNCTION public.submit_duel_results(duel_id bigint, challenger_won boolean, player_score_changes json)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
    duel_status duel_status;
    winner_id bigint;
    winner_display_name text;
    loser_id bigint;
    loser_display_name text;
    duel_round_number smallint;
    duel_game_name text;
    duel_round_submit_id bigint;
    player_id bigint;
    transaction_description text;
    player_score bigint;
BEGIN
    IF challenger_won THEN
        duel_status := 'challenger_won';
        winner_id := (SELECT challenger_player_id FROM duel WHERE id = duel_id);
        loser_id := (SELECT opponent_player_id FROM duel WHERE id = duel_id);
    ELSE
        duel_status := 'opponent_won';
        winner_id := (SELECT opponent_player_id FROM duel WHERE id = duel_id);
        loser_id := (SELECT challenger_player_id FROM duel WHERE id = duel_id);
    END IF;

    SELECT round_number, game_name, round_submit_id
    INTO duel_round_number, duel_game_name, duel_round_submit_id
    FROM duel
    WHERE id = duel_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'This duel no longer exists. Reload the page.';
    END IF;

    SELECT u.display_name
    INTO winner_display_name
    FROM player p
    JOIN "user" u ON p.user_id = u.id
    WHERE p.id = winner_id;

    SELECT u.display_name
    INTO loser_display_name
    FROM player p
    JOIN "user" u ON p.user_id = u.id
    WHERE p.id = loser_id;

    FOR player_id, player_score IN SELECT * FROM json_each_text(player_score_changes)
    LOOP
        INSERT INTO transaction (player_id, num_points, description, round_submit_id, created_at, updated_at)
        VALUES (player_id, player_score,
            CASE WHEN (player_id = winner_id)
                THEN 'Duel in turn ' || duel_round_number || ': You beat ' || loser_display_name || ' in ' || duel_game_name
                ELSE 'Duel in turn ' || duel_round_number || ': ' || winner_display_name || ' beat you in ' || duel_game_name
            END,
            duel_round_submit_id,
            now(), now()
        );

        IF player_id = winner_id THEN
            UPDATE duel
            SET points_gained_by_winner = player_score
            WHERE id = duel_id;
        END IF;
    END LOOP;

    UPDATE duel
    SET status = duel_status
    WHERE id = duel_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.submit_special_space_event_score(special_space_event_id bigint, score bigint)
 RETURNS void
 LANGUAGE plpgsql
AS $function$DECLARE
    player_id_val bigint;
    session_points_per_game_point_val float;
    space_name_val text;
    points_label_plural_val text;
    template_name_val text;
    round_number_val smallint;
    round_submit_id_val bigint;
BEGIN
    UPDATE public.special_space_event
    SET status = 'finished',
        results = jsonb_build_object('score', score)
    WHERE id = special_space_event_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'This space event no longer exists. Reload the page.';
    END IF;

    SELECT player_id, round_number, round_submit_id INTO player_id_val, round_number_val, round_submit_id_val
    FROM public.special_space_event
    WHERE id = special_space_event_id;

    SELECT sset.details->>'sessionPointsPerGamePoint' INTO session_points_per_game_point_val
    FROM public.special_space_event sse
    JOIN public.special_space_event_template sset ON sse.template_id = sset.id
    WHERE sse.id = special_space_event_id;

    SELECT gs.name, sset.details->>'pointsLabelPlural', sset.name
    INTO space_name_val, points_label_plural_val, template_name_val
    FROM public.special_space_event sse
    JOIN public.gameboard_space gs ON sse.special_space_id = gs.id
    JOIN public.special_space_event_template sset ON sse.template_id = sset.id
    WHERE sse.id = special_space_event_id;

    INSERT INTO public.transaction (player_id, num_points, description, round_submit_id)
    VALUES (player_id_val, score * session_points_per_game_point_val,
    space_name_val || ' Space event for turn ' || round_number_val || ': ' || score || ' ' || points_label_plural_val || ' in ' || template_name_val,
    round_submit_id_val);

END;$function$;

CREATE OR REPLACE FUNCTION public.submit_space_event_player_score_changes(space_event_id bigint, space_event_template_id bigint, player_score_changes json, event_description text, is_chaos_space_event boolean, add_lost_points_to_bank_balance boolean DEFAULT false)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
    player_id bigint;
    points bigint;
    round_num smallint;
    display_name_of_player_who_landed_on_space text;
    space_name text;
    v_round_submit_id bigint;
BEGIN
    IF is_chaos_space_event THEN
        SELECT u.display_name, cse.round_number, gs.name, cse.round_submit_id
        INTO display_name_of_player_who_landed_on_space, round_num, space_name, v_round_submit_id
        FROM "user" u
        JOIN player p ON u.id = p.user_id
        JOIN chaos_space_event cse ON p.id = cse.player_id
        JOIN gameboard_space gs ON cse.chaos_space_id = gs.id
        WHERE cse.id = space_event_id;
    ELSE
        SELECT u.display_name, sse.round_number, gs.name, sse.round_submit_id
        INTO display_name_of_player_who_landed_on_space, round_num, space_name, v_round_submit_id
        FROM "user" u
        JOIN player p ON u.id = p.user_id
        JOIN special_space_event sse ON p.id = sse.player_id
        JOIN gameboard_space gs ON sse.special_space_id = gs.id
        WHERE sse.id = space_event_id;
    END IF;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'This space event no longer exists. Reload the page.';
    END IF;

    FOR player_id, points IN SELECT * FROM json_each_text(player_score_changes) LOOP
        IF points <> 0 THEN
            INSERT INTO transaction (player_id, num_points, description, round_submit_id, lost_to_bank, created_at, updated_at)
            VALUES (player_id, points, display_name_of_player_who_landed_on_space || '''s ' || space_name || ' Space event for turn ' || round_num || ': ' || event_description,
                v_round_submit_id,
                add_lost_points_to_bank_balance AND points < 0,
                now(), now());
        END IF;
    END LOOP;

    IF is_chaos_space_event THEN
        UPDATE chaos_space_event
        SET template_id = space_event_template_id, status = 'finished', results = player_score_changes
        WHERE id = space_event_id;
    ELSE
        UPDATE special_space_event
        SET template_id = space_event_template_id, status = 'finished', results = player_score_changes
        WHERE id = space_event_id;
    END IF;
END;
$function$;

CREATE OR REPLACE FUNCTION public.override_points(data json, add_lost_points_to_bank_balance boolean)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
    player_id bigint := (data->>'playerId')::bigint;
    change_amount bigint := (data->>'change')::bigint;
    replace_value boolean := (data->>'replace')::boolean;
    comment_text text := (data->>'comment');
    player_score bigint;
    v_transaction_amount BIGINT;
BEGIN
    SELECT score INTO player_score FROM player WHERE id = player_id;

    IF replace_value THEN
        v_transaction_amount := change_amount - player_score;
    ELSE
        v_transaction_amount := change_amount;
    END IF;

    INSERT INTO transaction (player_id, num_points, description, lost_to_bank)
    VALUES (player_id, v_transaction_amount,
        CASE WHEN comment_text = '' THEN 'GM Discretion' ELSE 'GM Discretion: ' || comment_text END,
        v_transaction_amount < 0 AND add_lost_points_to_bank_balance);
END;
$function$;

create table public.round_submit (
  id bigint generated by default as identity primary key,
  session_id bigint not null
    references public.session (id) on update cascade on delete cascade,
  round_number smallint not null,
  phase public.round_phase not null,
  bank_paid_out bigint not null default 0,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint round_submit_session_id_round_number_phase_key
    unique (session_id, round_number, phase),
  constraint round_submit_phase_check
    check (phase in ('gameboard_moves', 'event')),
  constraint round_submit_bank_paid_out_check check (bank_paid_out >= 0)
);


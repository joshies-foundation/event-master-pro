create function public.check_bank_balance()
  returns trigger
  language plpgsql
as $function$
begin
    if (select bank_balance from public.session where id = new.id) < 0 then
        raise exception 'The bank balance cannot go below 0'
          using errcode = 'check_violation';
    end if;
    return null;
end;
$function$;

